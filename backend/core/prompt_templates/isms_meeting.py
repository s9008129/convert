# ---------------------------------------------------------------------------
# 表單欄位抽取器（純文字處理；由本文標籤式 Markdown 確定性抽出欄位 dict，
# 供 docx_converter 依 FormLayoutSpec 組裝官方會議記錄表版面）
# ---------------------------------------------------------------------------

_MISSING_CONFIRM = "（待確認）"

# 全部欄位鍵（同時是 LLM 輸出契約的標籤，順序照官方範本）
ISMS_FORM_FIELD_KEYS = (
    "機關名稱", "專案名稱", "會議議題", "地點", "主席", "日期", "記錄",
    "機關單位", "廠商單位", "參加人員", "內容", "追蹤事項", "決議事項", "臨時動議",
)

# 單行欄位：值取標籤同行冒號後文字
_INLINE_KEYS = frozenset(
    ("機關名稱", "專案名稱", "地點", "主席", "日期", "記錄", "機關單位", "廠商單位")
)

# 標籤比對：容錯標籤內空白（官方範本「地　　點」等全形空白對齊，
# Unicode 模式 \s 可匹配全形空白）、全半形冒號與常見同義標籤
_LABEL_SPECS = (
    ("機關名稱", r"機關名稱"),
    ("專案名稱", r"專案名稱"),
    ("會議議題", r"會議議題"),
    ("地點", r"地\s*點"),
    ("主席", r"主\s*席|主持人"),
    ("日期", r"日\s*期"),
    ("記錄", r"[記紀]\s*錄"),
    ("機關單位", r"機關單位"),
    ("廠商單位", r"廠商單位"),
    ("參加人員", r"參加人員"),
    ("內容", r"內\s*容"),
    ("追蹤事項", r"追蹤事項"),
    ("決議事項", r"決議事項"),
    ("臨時動議", r"臨時動議"),
)
_LABEL_PATTERNS = tuple(
    (key, re.compile(rf"^(?:{alternatives})\s*[:：]\s*(.*)$"))
    for key, alternatives in _LABEL_SPECS
)

# 掃描終止行：之後為附錄／原始逐字稿區，不屬表單欄位
_TERMINATOR_PREFIXES = ("## ", "<details", "</details")
_TERMINATOR_LINES = frozenset(("---", "***", "___"))


def _is_terminator(stripped_line: str) -> bool:
    """判斷是否為表單欄位掃描終止行（水平線／附錄標題／details 標籤）。"""
    if stripped_line in _TERMINATOR_LINES:
        return True
    return any(stripped_line.startswith(prefix) for prefix in _TERMINATOR_PREFIXES)


def _match_label(stripped_line: str):
    """比對欄位標籤行；命中回傳 (欄位鍵, 同行值)，未命中回傳 None。"""
    for key, pattern in _LABEL_PATTERNS:
        match = pattern.match(stripped_line)
        if match:
            return key, match.group(1).strip()
    return None


def extract_form_fields(record_md: str) -> dict[str, str]:
    """由 ISMS 月工作會議紀錄本文 Markdown 抽出表單欄位 dict。

    - 單行欄位取標籤同行冒號後值；多行欄位收集後續行直到下一個標籤行
      或掃描終止行（水平線後為逐字稿附錄，不得吞入欄位）。
    - 回傳 dict 保證 ISMS_FORM_FIELD_KEYS 全鍵存在；缺漏或空值填
      「（待確認）」，永不拋例外（表單品質問題不得阻斷 DOCX 下載）。
    """
    fields: dict[str, str] = {key: "" for key in ISMS_FORM_FIELD_KEYS}
    try:
        lines = (record_md or "").split("\n")
        total = len(lines)
        idx = 0
        while idx < total:
            stripped = lines[idx].strip()
            # 跳過空行與前置的「# 標題」行（result_title）
            if not stripped or stripped.startswith("# "):
                idx += 1
                continue
            if _is_terminator(stripped):
                break
            matched = _match_label(stripped)
            if matched is None:
                idx += 1
                continue

            key, inline_value = matched
            if key in _INLINE_KEYS:
                if inline_value and not fields[key]:
                    fields[key] = inline_value
                idx += 1
                continue

            # 多行欄位：同行殘值作第一行，續收至下一標籤行或終止行
            block: list[str] = [inline_value] if inline_value else []
            idx += 1
            while idx < total:
                next_stripped = lines[idx].strip()
                if _is_terminator(next_stripped) or _match_label(next_stripped) is not None:
                    break
                block.append(next_stripped)
                idx += 1
            while block and not block[-1]:
                block.pop()
            while block and not block[0]:
                block.pop(0)
            if block and not fields[key]:
                fields[key] = "\n".join(block)
    except Exception as e:  # noqa: BLE001 — 欄位抽取永不阻斷 DOCX 輸出
        log.error(f"[ISMS表單] 欄位抽取失敗，缺漏欄位以（待確認）代替: {e}")

    return {
        key: (value.strip() if value and value.strip() else _MISSING_CONFIRM)
        for key, value in fields.items()
    }
